#!/usr/bin/env python3
"""Regenerate the panel icon set from config/panel/icons.txt.

Usage:  python3 tools/gen_icons.py        (needs: pip install fonttools)

Reads icon names from config/panel/icons.txt, looks their codepoints up in
font/materialdesignicons-webfont.ttf and writes:

  config/panel/icon_glyphs.yaml   glyph list of the mdi_36 font (base_logic.yaml)
  config/panel/panel_icons.h      name -> glyph table used by panel_cards.h
  config/panel/configurator.js    ICON_GROUPS block (between the markers)
  config/panel/configurator.css   embedded WOFF subset for the web editor
                                  previews (between the markers)
"""

import base64
import io
import re
import sys
from pathlib import Path

try:
    from fontTools import subset
    from fontTools.ttLib import TTFont
except ImportError:
    sys.exit("fontTools is required: pip install fonttools")

ROOT = Path(__file__).resolve().parent.parent
PANEL = ROOT / "config" / "panel"
FONT = ROOT / "font" / "materialdesignicons-webfont.ttf"
SOURCE = PANEL / "icons.txt"

# Names that were stored on devices before icons.txt existed and are not MDI
# names. Mapped to the glyph they used to show.
ALIASES = {
    "kitchen": "silverware-fork-knife",
    "shutter": "window-shutter",
    "weather": "weather-partly-cloudy",
}

# Glyphs used by panel_cards.h directly (type defaults), always compiled in.
REQUIRED = ["lightbulb", "gauge", "gesture-tap-button", "folder-outline", "alarm-light", "chart-line"]

JS_BEGIN, JS_END = "// <generated:icons>", "// </generated:icons>"
CSS_BEGIN, CSS_END = "/* <generated:icon-font> */", "/* </generated:icon-font> */"


def read_groups():
    groups, current = [], None
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("##"):
            current = (line[2:].strip(), [])
            groups.append(current)
            continue
        if line.startswith("#"):
            continue
        if current is None:
            current = ("Інше", [])
            groups.append(current)
        current[1].append(line)
    return [g for g in groups if g[1]]


def replace_block(path, begin, end, body):
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(r"^([ \t]*)" + re.escape(begin) + r".*?" + re.escape(end), re.S | re.M)
    if not pattern.search(text):
        sys.exit(f"{path}: markers {begin} ... {end} not found")
    text = pattern.sub(lambda m: f"{m[1]}{begin}\n{body}\n{m[1]}{end}", text)
    path.write_text(text, encoding="utf-8")


def main():
    font = TTFont(FONT)
    by_name = {name: cp for cp, name in font.getBestCmap().items() if cp >= 0xF0000}

    groups = read_groups()
    seen, errors = set(), []
    for _, names in groups:
        for name in names:
            if name not in by_name:
                errors.append(f"unknown icon: {name}")
            if name in seen:
                errors.append(f"duplicate icon: {name}")
            seen.add(name)
    if errors:
        sys.exit("\n".join(errors))

    extra = [n for n in REQUIRED + list(ALIASES.values()) if n not in seen]
    if extra:
        groups.append(("Інше", extra))
        seen.update(extra)

    names = [n for _, ns in groups for n in ns]
    codepoints = sorted({by_name[n] for n in names})

    # --- firmware font glyphs
    lines = ["# Generated by tools/gen_icons.py from config/panel/icons.txt. Do not edit.", ""]
    lines += [f'- "\\U{cp:08X}"  # {font.getBestCmap()[cp]}' for cp in codepoints]
    (PANEL / "icon_glyphs.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # --- firmware name table (sorted for binary search)
    table = sorted([(n, by_name[n]) for n in names] + [(a, by_name[t]) for a, t in ALIASES.items()])
    entries = "\n".join(f'    {{"{n}", "\\U{cp:08X}"}},' for n, cp in table)
    (PANEL / "panel_icons.h").write_text(
        "#pragma once\n"
        "// Generated by tools/gen_icons.py from config/panel/icons.txt. Do not edit.\n"
        "// Sorted by name; every glyph here is compiled into the mdi_36 font.\n\n"
        "namespace panel_cards {\n\n"
        "struct Icon {\n  const char *name;\n  const char *glyph;\n};\n\n"
        f"inline constexpr Icon kIcons[] = {{\n{entries}\n}};\n\n"
        "}  // namespace panel_cards\n",
        encoding="utf-8",
    )

    # --- web editor icon list
    js_groups = ",\n".join(
        f'    [{title!r}, "' + " ".join(f"{n}:{by_name[n]:X}" for n in ns) + '"]'
        for title, ns in groups
    ).replace("'", '"')
    replace_block(
        PANEL / "configurator.js",
        JS_BEGIN,
        JS_END,
        "  // Generated by tools/gen_icons.py from config/panel/icons.txt. Do not edit.\n"
        f"  const ICON_GROUPS = [\n{js_groups},\n  ];",
    )

    # --- web editor preview font (subset of MDI, embedded so it works offline)
    options = subset.Options()
    options.flavor = "woff"
    options.layout_features = []
    options.name_IDs = []
    options.notdef_outline = False
    options.glyph_names = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    sub = TTFont(FONT)
    subsetter.subset(sub)
    buf = io.BytesIO()
    sub.flavor = "woff"
    sub.save(buf)
    data = base64.b64encode(buf.getvalue()).decode()
    replace_block(
        PANEL / "configurator.css",
        CSS_BEGIN,
        CSS_END,
        "@font-face {\n  font-family: \"sp-mdi\";\n"
        f"  src: url(data:font/woff;base64,{data}) format(\"woff\");\n}}",
    )

    print(f"{len(names)} icons, {len(codepoints)} glyphs, preview font {len(buf.getvalue()) // 1024} KB")


if __name__ == "__main__":
    main()
