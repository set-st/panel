    // ----------------------------------------------------------- pages

    async function addPage() {
      if (state.pages.length >= MAX_PAGES) return;
      await run("Додавання сторінки", async () => {
        await writePages([...state.pages, { title: `Сторінка ${state.pages.length + 1}`, icon: "", nav: true }]);
        state.page = state.pages.length - 1;
      });
    }

    // Remaps page indexes in all cards (page field and subpage targets).
    async function remapCards(map) {
      for (let i = 0; i < SLOTS; i += 1) {
        const c = state.cards[i];
        if (!c) continue;
        const page = map(c.page);
        const target = c.type === "subpage" ? map(Number(c.entity)) : null;
        let next = { ...c, page };
        if (page === null || (c.type === "subpage" && target === null)) next = null;
        else if (c.type === "subpage") next.entity = String(target);
        if (serializeCard(next) !== serializeCard(c)) await writeSlot(i, next);
      }
    }

    async function deletePage(k) {
      if (k === 0) return;
      const count = state.cards.filter((c) => c && c.page === k).length;
      if (!confirm(`Видалити сторінку «${state.pages[k].title}»${count ? ` і ${count} карток на ній` : ""}?`)) return;
      await run("Видалення сторінки", async () => {
        await remapCards((p) => (p === k ? null : p > k ? p - 1 : p));
        await writePages(state.pages.filter((_, i) => i !== k));
        state.page = Math.min(k, state.pages.length - 1);
      });
    }

    async function movePage(k, dir) {
      const j = k + dir;
      if (k === 0 || j <= 0 || j >= state.pages.length) return;
      await run("Переміщення сторінки", async () => {
        await remapCards((p) => (p === k ? j : p === j ? k : p));
        const pages = state.pages.slice();
        [pages[k], pages[j]] = [pages[j], pages[k]];
        await writePages(pages);
        state.page = j;
      });
    }

    function renderPageBox() {
      const k = state.page;
      const p = state.pages[k];
      const title = el("input", { type: "text", maxlength: "24", value: p.title });
      const icon = iconPicker(p.icon, "Без іконки");
      const nav = el("input", { type: "checkbox", checked: p.nav });
      const save = () => run("Збереження сторінки", async () => {
        const pages = state.pages.map((x, i) => (i === k
          ? { title: clean(title.value) || x.title, icon: icon.value, nav: nav.checked }
          : x));
        await writePages(pages);
      });
      pageBox.replaceChildren(
        field("Назва сторінки", title),
        field("Іконка в меню", icon),
        el("label", { class: "sp-check" }, [nav, el("span", { text: "Показувати в нижньому меню" })]),
        el("div", { class: "sp-actions" }, [
          k > 0 ? el("button", { class: "sp-secondary", type: "button", text: "←", title: "Лівіше в меню", disabled: k <= 1, onclick: () => movePage(k, -1) }) : null,
          k > 0 ? el("button", { class: "sp-secondary", type: "button", text: "→", title: "Правіше в меню", disabled: k >= state.pages.length - 1, onclick: () => movePage(k, 1) }) : null,
          k > 0 ? el("button", { class: "sp-secondary sp-danger", type: "button", text: "Видалити сторінку", onclick: () => deletePage(k) }) : null,
          el("button", { class: "sp-primary", type: "button", text: "Зберегти сторінку", onclick: save }),
        ]),
      );
    }

