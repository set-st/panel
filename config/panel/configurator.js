    function showForm(index) {
      const existing = state.cards[index];
      const card = existing || { type: "toggle", entity: "", label: "", icon: "", page: state.page, size: 1 };
      const type = selectOf(TYPES, card.type);
      const entity = el("input", { type: "text", placeholder: "light.kitchen", autocomplete: "off" });
      entity.value = card.type === "subpage" ? "" : card.entity;
      const pageOptions = state.pages.map((p, i) => [String(i), p.title]);
      const target = selectOf(pageOptions, card.type === "subpage" ? card.entity : String(state.pages.length > 1 ? 1 : 0));
      const page = selectOf(pageOptions, card.page);
      const label = el("input", { type: "text", placeholder: "Назва на картці", maxlength: "40" });
      label.value = card.label;
      const icon = iconPicker(card.icon);
      const size = selectOf(SIZES, card.size || 1);
      const period = selectOf(PERIODS, card.period || 24);
      const periodField = field("Період графіка", period,
        "Панель збирає історію сама з моменту створення картки; після перезавантаження графік починається заново.");
      // Charts need numbers: hide entities whose state is text.
      const numeric = (e) => type.value !== "chart" || !Number.isNaN(Number.parseFloat(e.state))
        || ["unknown", "unavailable"].includes(e.state);
      const search = entitySearch(entity, () => TYPE_DOMAINS[type.value] ?? null, (e) => {
        if (!label.value.trim() && e.name) label.value = e.name;
      }, numeric);
      const entityField = field("Entity ID у Home Assistant", search.element,
        "Почніть вводити назву або entity ID (light.kitchen, sensor.bedroom_temperature, scene.movie)");
      const targetField = field("Відкрити сторінку", target, "Кнопка «Назад» на екрані повертає на попередню сторінку.");
      const alarmNote = el("p", {
        class: "sp-muted sp-wide",
        text: state.alarm
          ? `Показує стан тривоги з ${alarmAir(state.alarm)}. Джерело змінюється в «Налаштування панелі → Повітряна тривога».`
          : "Спочатку вкажіть сенсор регіону в «Налаштування панелі → Повітряна тривога» (внизу).",
      });
      const sync = () => {
        const sub = type.value === "subpage";
        const alarm = type.value === "alarm";
        entityField.hidden = sub || alarm;
        targetField.hidden = !sub;
        alarmNote.hidden = !alarm;
        periodField.hidden = type.value !== "chart";
      };
      type.addEventListener("change", () => {
        // A chart needs room: suggest 2×1 for a new card.
        if (!existing && type.value === "chart" && size.value === "1") size.value = "2";
        sync();
        search.refresh();
      });
      sync();

      const save = async () => {
        const next = {
          type: type.value,
          entity: type.value === "subpage" ? target.value
            : type.value === "alarm" ? "alarm"
            : entity.value.trim().toLowerCase(),
          label: label.value,
          icon: icon.value,
          page: Number(page.value),
          size: Number(size.value),
          period: Number(period.value),
        };
        if (next.type !== "subpage" && next.type !== "alarm" && !ENTITY_RE.test(next.entity)) {
          setStatus("Entity ID має виглядати як domain.object_id, наприклад light.kitchen", true);
          return;
        }
        if (next.type === "subpage" && Number(next.entity) === next.page) {
          setStatus("Картка не може відкривати сторінку, на якій сама знаходиться", true);
          return;
        }
        await run("Збереження картки", () => writeSlot(index, next));
        form.replaceChildren();
      };

      form.replaceChildren(
        el("section", { class: "sp-card-editor" }, [
          el("h3", { text: existing ? `Картка ${index + 1}` : "Нова картка" }),
          field("Тип", type),
          entityField,
          targetField,
          alarmNote,
          field("Підпис", label, "Порожньо — показується entity ID або назва сторінки"),
          field("Іконка", icon),
          periodField,
          field("Розмір", size),
          field("Сторінка", page),
          el("div", { class: "sp-actions" }, [
            el("button", { class: "sp-secondary", type: "button", text: "Скасувати", onclick: () => form.replaceChildren() }),
            el("button", { class: "sp-primary", type: "button", text: "Зберегти", onclick: save }),
          ]),
        ]),
      );
      form.scrollIntoView({ behavior: "smooth", block: "nearest" });
    }

