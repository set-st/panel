  function haGetStates(url, token) {
    return new Promise((resolve, reject) => {
      let ws;
      try {
        ws = new WebSocket(`${url.replace(/\/+$/, "").replace(/^http/, "ws")}/api/websocket`);
      } catch (e) {
        reject(new Error(`Невірна адреса Home Assistant: ${e.message}`));
        return;
      }
      const timer = setTimeout(() => { ws.close(); reject(new Error("Home Assistant не відповідає")); }, 10000);
      const done = (fn, value) => { clearTimeout(timer); ws.close(); fn(value); };
      ws.onerror = () => done(reject, new Error("Не вдалося підключитися до Home Assistant. Перевірте адресу (http/https, порт)."));
      ws.onmessage = (event) => {
        const msg = JSON.parse(event.data);
        if (msg.type === "auth_required") ws.send(JSON.stringify({ type: "auth", access_token: token }));
        else if (msg.type === "auth_invalid") done(reject, new Error("Home Assistant відхилив токен"));
        else if (msg.type === "auth_ok") ws.send(JSON.stringify({ id: 1, type: "get_states" }));
        else if (msg.type === "result" && msg.id === 1) {
          if (msg.success) done(resolve, msg.result);
          else done(reject, new Error(msg.error?.message || "Помилка get_states"));
        }
      };
    });
  }

  function loadHaEntities(force = false) {
    const { url, token } = haSettings();
    if (!url || !token) { ha.entities = null; ha.error = ""; return Promise.resolve(null); }
    if (ha.loading && !force) return ha.loading;
    if (ha.entities && !force) return Promise.resolve(ha.entities);
    ha.loading = haGetStates(url, token)
      .then((states) => {
        ha.entities = states
          .map((s) => ({
            id: s.entity_id,
            name: s.attributes?.friendly_name || "",
            state: s.state,
            unit: s.attributes?.unit_of_measurement || "",
          }))
          .sort((a, b) => a.id.localeCompare(b.id));
        ha.error = "";
        return ha.entities;
      })
      .catch((e) => { ha.entities = null; ha.error = e.message || String(e); return null; })
      .finally(() => { ha.loading = null; });
    return ha.loading;
  }

  // Turns a text input into a searchable entity field. domains() returns the
  // allowed domains (or null); onPick(entity) is called when one is chosen.
  function entitySearch(input, domains, onPick, accept = () => true) {
    const list = el("div", { class: "sp-entity-list", hidden: true });
    const wrap = el("div", { class: "sp-entity-search" });
    wrap.append(input, list);
    let active = -1;
    let hits = [];

    const choose = (entity) => {
      input.value = entity.id;
      list.hidden = true;
      onPick?.(entity);
    };

    const highlight = () => {
      [...list.children].forEach((node, i) => node.classList.toggle("sp-entity-active", i === active));
      list.children[active]?.scrollIntoView({ block: "nearest" });
    };

    const show = async () => {
      if (!ha.entities) await loadHaEntities();
      if (!ha.entities) {
        list.replaceChildren(el("div", { class: "sp-entity-note", text: ha.error
          ? `Пошук недоступний: ${ha.error}`
          : "Щоб шукати сутності, підключіть Home Assistant у розділі «Home Assistant» нижче." }));
        list.hidden = document.activeElement !== input;
        return;
      }
      const allowed = domains();
      const words = input.value.trim().toLowerCase().split(/\s+/).filter(Boolean);
      hits = ha.entities
        .filter((e) => (!allowed || allowed.includes(e.id.split(".")[0])) && accept(e))
        .filter((e) => words.every((w) => e.id.includes(w) || e.name.toLowerCase().includes(w)))
        .slice(0, 60);
      active = -1;
      list.replaceChildren(...(hits.length
        ? hits.map((e) => el("button", {
          type: "button",
          class: "sp-entity-item",
          onmousedown: (ev) => ev.preventDefault(),
          onclick: () => choose(e),
        }, [
          el("span", { class: "sp-entity-name", text: e.name || e.id }),
          el("span", { class: "sp-entity-id", text: e.id }),
          el("span", { class: "sp-entity-state", text: `${e.state}${e.unit ? ` ${e.unit}` : ""}` }),
        ]))
        : [el("div", { class: "sp-entity-note", text: "Нічого не знайдено" })]));
      list.hidden = document.activeElement !== input;
    };

    input.setAttribute("autocomplete", "off");
    input.addEventListener("focus", show);
    input.addEventListener("input", show);
    input.addEventListener("blur", () => { list.hidden = true; });
    input.addEventListener("keydown", (ev) => {
      if (list.hidden || !hits.length) return;
      if (ev.key === "ArrowDown" || ev.key === "ArrowUp") {
        ev.preventDefault();
        active = (active + (ev.key === "ArrowDown" ? 1 : -1) + hits.length) % hits.length;
        highlight();
      } else if (ev.key === "Enter" && active >= 0) {
        ev.preventDefault();
        choose(hits[active]);
      } else if (ev.key === "Escape") {
        list.hidden = true;
      }
    });
    return { element: wrap, refresh: show };
  }

